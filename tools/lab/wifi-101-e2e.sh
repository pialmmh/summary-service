#!/usr/bin/env bash
# The WiFi session (service group 101) through the outbox — ARCH-0077-S item 3, with the PACKAGED jar on the lab profile
# (btcl/lab: the twelve beans), on BOTH engines. The rule: a 101 record lands in sum_voice_day_101 / sum_voice_hr_101 ONLY —
# the 30 tables and the ad tables are unchanged by it — and sum_chargeable_* carries the 101 legs as it carries every
# group; the package minutes (TF_min) and the money (BDT) are two rows, never one; a session of 0 seconds is counted, not
# costed (the row with no unit).
#
#   tools/lab/wifi-101-e2e.sh [pg | mysql | both]     (default both)
#
# The labs are THIS BOX. PostgreSQL: the container SS_LAB_PG (default ss-pg16-lab) on 127.0.0.1:SS_LAB_PG_PORT (default
# 7643, tools/lab/pg-lab.sh up; trust — no password exists). MySQL: 127.0.0.1:SS_LAB_MYSQL_PORT (default 7633, the lab's
# own container, root, no password); a MySQL that needs one takes it by the NAME of a variable, SS_LAB_MYSQL_PASSWORD_VAR=<NAME>:
# the service gets summary.store.password-ref=env:<NAME> and this script's client reads the same variable — the value is on
# no command line and in no output. The service is started by tools/lab/run-lab.sh (the endpoints shown first; every host
# this box; the lab profile's Kafka is not needed — the workers drain on the poll). Maven reads MAVEN_ARGS (a private
# repository's flags) when the row tool's classpath has to be built. What the story makes is removed at the end; the
# containers stay.
set -euo pipefail
cd "$(dirname "$0")/../.."

ENGINES=${1:-both}
PG=${SS_LAB_PG:-ss-pg16-lab}; PG_PORT=${SS_LAB_PG_PORT:-7643}
MY_HOST=127.0.0.1; MY_PORT=${SS_LAB_MYSQL_PORT:-7633}; MY_USER=${SS_LAB_MYSQL_USER:-root}; MY_PASSWORD_VAR=${SS_LAB_MYSQL_PASSWORD_VAR:-}
SCHEMA=lab_wifi101
MINUTES=7; MONEY=3; ZERO=2; VIEWS=5            # the sessions paid from the bucket / in money / of zero seconds; the ad views before them
WORK=target/lab-e2e; JAR=target/quarkus-app/quarkus-run.jar
mkdir -p "$WORK"
[ -f "$JAR" ] || { echo "no packaged application — run: mvn package -DskipTests"; exit 2; }

say() { printf '\n== %s ==\n' "$*"; }
service_pid=""
stop_service() { [ -n "$service_pid" ] && kill "$service_pid" 2>/dev/null || true; service_pid=""; sleep 2; }
pg()  { local role=$1; shift; docker exec -i "$PG" psql -U "$role" -d routesphere -q -v ON_ERROR_STOP=1 "$@"; }
pgv() { docker exec -i "$PG" psql -U "$1" -d routesphere -tA -c "$2" 2>/dev/null; }
my()  { if [ -n "$MY_PASSWORD_VAR" ]; then MYSQL_PWD="${!MY_PASSWORD_VAR}" mysql -h "$MY_HOST" -P "$MY_PORT" -u "$MY_USER" -N "$@"; else mysql -h "$MY_HOST" -P "$MY_PORT" -u "$MY_USER" -N "$@"; fi; }
myv() { my -e "$1" 2>/dev/null; }
cleanup() {
  stop_service
  pg postgres -c "DROP SCHEMA IF EXISTS $SCHEMA CASCADE" >/dev/null 2>&1 || true
  myv "DROP DATABASE IF EXISTS $SCHEMA" >/dev/null 2>&1 || true
}
trap cleanup EXIT
cleanup

[ -s "$WORK/cp.txt" ] || mvn -o -q dependency:build-classpath -Dmdep.outputFile="$WORK/cp.txt" -Dmdep.includeScope=test >/dev/null
row() { java -cp "target/classes:target/test-classes:$(cat "$WORK/cp.txt")" com.telcobright.summary.testkit.LabOutboxRow "$1" 2>/dev/null; }
ROW_VIEW=$(row ad); ROW_MINUTES=$(row wifi-minutes); ROW_MONEY=$(row wifi-money); ROW_ZERO=$(row wifi-zero)   # each ONE record, as billing-core writes it

# ---- one engine's story ------------------------------------------------------------------------------------------
setup_pg() {
  pg prime_context -c "CREATE SCHEMA $SCHEMA" -c "GRANT USAGE, CREATE ON SCHEMA $SCHEMA TO summary_service, billing_core" \
     -c "ALTER DEFAULT PRIVILEGES FOR ROLE summary_service IN SCHEMA $SCHEMA GRANT SELECT ON TABLES TO ad_sphere" >/dev/null 2>&1
  pg billing_core <<SQL
SET search_path TO $SCHEMA;
CREATE TABLE cdr (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, servicegroup int NOT NULL);
CREATE TABLE summary_affected (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, entity_type varchar(32) NOT NULL,
  op varchar(8) NOT NULL DEFAULT 'add' CHECK (op IN ('add', 'subtract')), data text NOT NULL);
GRANT SELECT, DELETE ON summary_affected TO summary_service;
SQL
  OPTIONS=(-Dsummary.tenants.mode=single "-Dsummary.store.url=jdbc:postgresql://127.0.0.1:$PG_PORT/routesphere?currentSchema=$SCHEMA")
}
setup_mysql() {
  myv "CREATE DATABASE $SCHEMA" >/dev/null
  myv "CREATE TABLE $SCHEMA.cdr (id bigint AUTO_INCREMENT PRIMARY KEY, servicegroup int NOT NULL)" >/dev/null
  # the lab's partition horizon (the rows are of October 2026): twelve tables of 731 daily partitions each take minutes on a busy box
  OPTIONS=(-Dsummary.tenants.mode=single -Dsummary.store.kind=mysql "-Dsummary.store.username=$MY_USER"
           -Dsummary.ddl.partition-start=2026-09-01 -Dsummary.ddl.partition-days=60
           "-Dsummary.store.url=jdbc:mysql://$MY_HOST:$MY_PORT/$SCHEMA?useSSL=false&allowPublicKeyRetrieval=true&allowMultiQueries=true")
  [ -n "$MY_PASSWORD_VAR" ] && OPTIONS+=("-Dsummary.store.password-ref=env:$MY_PASSWORD_VAR")
  true
}
write_rows() {   # $1 engine, $2 service group, $3 how many, $4 the record: ONE cdr row and ONE outbox row each, in ONE transaction (as billing-core writes)
  if [ "$1" = pg ]; then
    pgv billing_core "INSERT INTO $SCHEMA.cdr (servicegroup) SELECT $2 FROM generate_series(1, $3); INSERT INTO $SCHEMA.summary_affected (entity_type, op, data) SELECT 'cdr', 'add', '$4' FROM generate_series(1, $3)" >/dev/null
  else
    myv "START TRANSACTION; INSERT INTO $SCHEMA.cdr (servicegroup) SELECT $2 FROM (SELECT 1 FROM information_schema.columns a, information_schema.columns b LIMIT $3) n; INSERT INTO $SCHEMA.summary_affected (entity_type, op, data) SELECT 'cdr', 'add', '$4' FROM (SELECT 1 FROM information_schema.columns a, information_schema.columns b LIMIT $3) n; COMMIT" >/dev/null
  fi
}
q() { if [ "$1" = pg ]; then pgv postgres "$2"; else myv "$2"; fi; }     # a read as the lab's superuser
written()  { q "$1" "select coalesce(max(id),0) from $SCHEMA.summary_affected"; }
caughtUp() { q "$1" "select count(*) from $SCHEMA.summary_offset where last_offset >= $2"; }   # how many of the twelve beans are at the last outbox row
waitCaughtUp() {   # $1 engine, $2 seconds at most
  local last; last=$(written "$1"); local started; started=$(date +%s)
  for _ in $(seq 1 $(( $2 * 5 ))); do
    if [ "$(caughtUp "$1" "$last")" = "12" ]; then echo "$(( $(date +%s) - started )) s: 12 of 12 beans at outbox row $last"; return 0; fi
    sleep 0.2
  done
  echo "NOT CAUGHT UP after $2 s: $(caughtUp "$1" "$last") of 12 beans at row $last"; return 1
}
rowsOf() {   # $1 engine, $2 a voice table: every row as one text (payer | unit | calls | cost), to see that nothing of it changed
  if [ "$1" = pg ]; then q pg "select coalesce(string_agg(concat_ws('|', tup_inpartnerid, tup_customercurrency, totalcalls, customercost), ';' order by id), '') from $SCHEMA.$2"
  else q mysql "select ifnull(group_concat(concat_ws('|', tup_inpartnerid, tup_customercurrency, totalcalls, customercost) order by id separator ';'), '') from $SCHEMA.$2"; fi
}
voice() {   # $1 engine, $2 a voice table, $3 the unit: "calls|charged|cost" of that unit's row
  q "$1" "select coalesce((select concat_ws('|', totalcalls, successfulcalls, customercost) from $SCHEMA.$2 where tup_customercurrency = '$3'), 'none')"
}
chargeable() {   # $1 engine, $2 a chargeable table, $3 the group, $4 the unit: "legs|amount" (BilledAmount is DECIMAL(18,8) there)
  q "$1" "select concat_ws('|', sum(totalcount), sum(BilledAmount)) from $SCHEMA.$2 where tup_servicegroup = $3 and tup_billeduom = '$4'"
}
check() { if [ "$2" = "$3" ]; then echo "ok    $1 = $3"; else echo "FAIL  $1: expected $2, read $3"; verdict=1; fi; }
start_service() {   # $1 engine, $2 log; waits for the start's verdict
  tools/lab/run-lab.sh btcl/lab "${OPTIONS[@]}" > "$2" 2>&1 &
  service_pid=$!
  for _ in $(seq 1 480); do grep -q "is served: 12 of 12\|could NOT be served\|NOT STARTED\|REFUSING" "$2" && break; sleep 0.5; done
}

story() {
  local engine=$1
  local log="$WORK/wifi-101-$engine.log" verdict=0 day30 hr30 table

  say "$engine · 1 · the service serves $SCHEMA with the lab profile's twelve beans"
  "setup_$engine"
  start_service "$engine" "$log"
  grep -q "is served: 12 of 12" "$log" || { echo "not served:"; grep -E "ERROR|REFUS|NOT STARTED" "$log" | tail -8 | cut -c1-260; return 1; }
  grep -E "^ENDPOINT |^SECRET " "$log" | cut -c1-200
  grep "bean registered" "$log" | grep -o "name=[A-Za-z0-9]* .*table=[a-z_0-9]*" | grep 101 | sed 's/^/   /'
  if [ "$engine" = mysql ]; then for _ in $(seq 1 60); do [ -n "$(myv "show tables in $SCHEMA like 'summary_affected'")" ] && break; sleep 0.5; done; fi

  say "$engine · 2 · $VIEWS ad views (group 30) first; the 30 tables and the ad table as they stand after them"
  write_rows "$engine" 30 "$VIEWS" "$ROW_VIEW"
  waitCaughtUp "$engine" 60 || return 1
  day30=$(rowsOf "$engine" sum_voice_day_30); hr30=$(rowsOf "$engine" sum_voice_hr_30)
  echo "sum_voice_day_30: $day30"; echo "sum_voice_hr_30: $hr30"
  echo "sum_ad_day_30 views: $(q "$engine" "select coalesce(sum(views),0) from $SCHEMA.sum_ad_day_30")"

  say "$engine · 3 · $MINUTES sessions paid from the bucket (30 TF_min each), $MONEY paid in money (3.00 BDT each), $ZERO of zero seconds — $((MINUTES + MONEY + ZERO)) records of group 101"
  write_rows "$engine" 101 "$MINUTES" "$ROW_MINUTES"
  write_rows "$engine" 101 "$MONEY" "$ROW_MONEY"
  write_rows "$engine" 101 "$ZERO" "$ROW_ZERO"
  waitCaughtUp "$engine" 90 || verdict=1

  say "$engine · 4 · the 101 tables: the sessions — minutes and money apart, the zero-second ones counted and not costed"
  for table in sum_voice_day_101 sum_voice_hr_101; do
    check "$table TF_min row (calls|charged|cost)" "$MINUTES|$MINUTES|$((MINUTES * 30)).000000" "$(voice "$engine" "$table" TF_min)"
    check "$table BDT row (calls|charged|cost)" "$MONEY|$MONEY|$((MONEY * 3)).000000" "$(voice "$engine" "$table" BDT)"
    check "$table no-unit row: the 0-s sessions (calls|charged|cost)" "$ZERO|0|0.000000" "$(voice "$engine" "$table" '')"
    check "$table rows" "3" "$(q "$engine" "select count(*) from $SCHEMA.$table")"
  done
  check "sum_voice_day_101 calls = the cdr rows of group 101" "$(q "$engine" "select count(*) from $SCHEMA.cdr where servicegroup = 101")" \
        "$(q "$engine" "select coalesce(sum(totalcalls),0) from $SCHEMA.sum_voice_day_101")"

  say "$engine · 5 · the 30 tables and the ad tables: unchanged by the sessions"
  check "sum_voice_day_30 as it stood before the sessions" "$day30" "$(rowsOf "$engine" sum_voice_day_30)"
  check "sum_voice_hr_30 as it stood before the sessions" "$hr30" "$(rowsOf "$engine" sum_voice_hr_30)"
  check "sum_voice_day_30 calls = the views" "$VIEWS" "$(q "$engine" "select coalesce(sum(totalcalls),0) from $SCHEMA.sum_voice_day_30")"
  check "sum_ad_day_30 views" "$VIEWS" "$(q "$engine" "select coalesce(sum(views),0) from $SCHEMA.sum_ad_day_30")"
  check "sum_ad_hr_30 views" "$VIEWS" "$(q "$engine" "select coalesce(sum(views),0) from $SCHEMA.sum_ad_hr_30")"

  say "$engine · 6 · sum_chargeable_*: the 101 legs beside the 30 ones, as every group (legs|amount)"
  for table in sum_chargeable_day sum_chargeable_hr; do
    check "$table group 101 TF_min (the bucket sessions and the 0-s ones at 0 TF_min)" "$((MINUTES + ZERO))|$((MINUTES * 30)).00000000" "$(chargeable "$engine" "$table" 101 TF_min)"
    check "$table group 101 BDT" "$MONEY|$((MONEY * 3)).00000000" "$(chargeable "$engine" "$table" 101 BDT)"
    check "$table group 30 BDT (the views at 0.50)" "$VIEWS|$(awk "BEGIN {printf \"%.8f\", $VIEWS * 0.5}")" "$(chargeable "$engine" "$table" 30 BDT)"
  done
  echo "ERROR lines of the service: $(grep -c " ERROR " "$log" || true) (the ping listener's broker is not in this lab: a WARN, the workers drain on the poll)"
  stop_service

  [ "$verdict" = 0 ] && echo "$engine HOLDS: the sessions in the 101 tables only, minutes and money apart, the 30 and ad tables unchanged, the chargeable tables carrying the 101 legs" \
                     || echo "$engine DOES NOT HOLD — see above (log: $log)"
  return "$verdict"
}

result=0
case "$ENGINES" in
  pg)    story pg || result=1 ;;
  mysql) story mysql || result=1 ;;
  both)  story pg || result=1; cleanup; story mysql || result=1 ;;
  *)     echo "usage: $0 [pg | mysql | both]"; exit 2 ;;
esac
echo; [ "$result" = 0 ] && echo "ARCH-0077-S item 3 HOLDS on $ENGINES: 101 records through the outbox land in sum_voice_day_101 / sum_voice_hr_101 only; the 30 tables unchanged; sum_chargeable_* carries the 101 legs." \
                        || echo "ARCH-0077-S item 3 DOES NOT HOLD — see above."
echo "removing: the service, the schema / database (the containers stay)"
exit "$result"
